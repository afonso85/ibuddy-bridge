<#
.SYNOPSIS
  Installs (or removes) the iBuddy Bridge autostart.

.DESCRIPTION
  Writes a .vbs file into the Windows Startup folder that launches the daemon
  hidden, with no window, at every logon. The paths (project and Python) are
  resolved on this machine - nothing is hardcoded in the repository.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1
  powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1 -Remove
#>
param([switch]$Remove)

$ErrorActionPreference = "Stop"
$project = Split-Path -Parent $PSScriptRoot
$target  = Join-Path ([Environment]::GetFolderPath("Startup")) "iBuddyBridge.vbs"

if ($Remove) {
    if (Test-Path $target) {
        Remove-Item $target
        Write-Host "Autostart removed: $target"
    } else {
        Write-Host "Nothing to remove ($target does not exist)."
    }
    return
}

$python = (Get-Command python -ErrorAction Stop).Source
$daemon = Join-Path $project "run_daemon.py"
if (-not (Test-Path $daemon)) { throw "run_daemon.py not found in $project" }

$vbs = @"
' Generated by scripts/install-autostart.ps1 - launches the iBuddy Bridge daemon with no window.
Set shell = CreateObject("WScript.Shell")
shell.CurrentDirectory = "$project"
shell.Run """$python"" ""$daemon""", 0, False
"@

# UTF-16 (with BOM): Windows Script Host reads paths with accented characters correctly
Set-Content -Path $target -Value $vbs -Encoding Unicode

Write-Host "Autostart installed: $target"
Write-Host "  Python : $python"
Write-Host "  Daemon : $daemon"
Write-Host "To start it now, without restarting Windows:  cscript //nologo `"$target`""
Write-Host "To remove it:  powershell -ExecutionPolicy Bypass -File scripts\install-autostart.ps1 -Remove"
